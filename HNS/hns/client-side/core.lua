-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("hns",Creative)
vSERVER = Tunnel.getInterface("hns")
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local Opened = false
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLOSEPANEL
-----------------------------------------------------------------------------------------------------------------------------------------
local ClosePanel = function()
	Opened = false
	SetNuiFocus(false,false)
	SetCursorLocation(0.5,0.5)
	TransitionFromBlurred(1000)
	TriggerEvent("hud:Active",true)
	SendNUIMessage({ Action = "Close" })
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- HNS:OPENED
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("hns:Opened")
AddEventHandler("hns:Opened",function()
	local Player = vSERVER.Player()
	if not Player then
		return false
	end

	Opened = true
	SetNuiFocus(true,true)
	SetCursorLocation(0.5,0.5)
	TransitionToBlurred(1000)
	TriggerEvent("hud:Active",false)

	SendNUIMessage({
		Action = "Open",
		Payload = {
			PlayerName = Player.Name,
			Avatar = Player.Avatar,
			Theme = Config.Theme
		}
	})
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- HNS:CLOSE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("hns:Close")
AddEventHandler("hns:Close",function()
	ClosePanel()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLOSENUI
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("closeNUI",function(Data,Callback)
	ClosePanel()

	Callback("Ok")
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- COMMAND
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand(Config.Command,function()
	if Opened then
		ClosePanel()
	else
		TriggerServerEvent("hns:Open")
	end
end,false)

if Config.Key then
	RegisterKeyMapping(Config.Command,Config.CommandDescription,"keyboard",Config.Key)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- EXPORTS
-----------------------------------------------------------------------------------------------------------------------------------------
exports("Opened",function()
	return Opened
end)
